const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

const key = 'mis-finanzas-offline-v1';
const url = process.env.APP_URL || 'http://127.0.0.1:8767/';
const fixture = { version: 1, device: 'integracion-ficticia', revision: 0, updatedAt: '2026-11-02T00:00:00Z',
  accounts: [{ id: 'cash', name: 'Caja ficticia', type: 'cash', opening: 2000000 }, { id: 'bank', name: 'Banco ficticio', type: 'bank', opening: 1000000 }],
  lists: [{ id: 'home', name: 'Hogar ficticio' }], categories: ['Compras', 'Otros'], transactions: [],
  budgets: [{ id: 'budget', category: 'Compras', amount: 2000000 }], goals: [{ id: 'goal', name: 'Meta ficticia', target: 5000, saved: 300 }], debts: [], settings: {} };

async function run(width) {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width, height: 900 }, serviceWorkers: 'block' });
    await page.clock.install({ time: new Date('2026-11-02T12:00:00Z') });
    await page.route('https://accounts.google.com/**', route => route.abort());
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(({ key, fixture }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(fixture)); }, { key, fixture });
    await page.goto(url);
    const nav = width < 1024 ? '#nav' : '#desktopNav';
    const saved = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
    const openNew = async () => { if (width < 1024) await page.locator('#add').click(); };
    const saveMovement = async (entry, type, status = 'done') => {
      await openNew();
      const form = page.locator('#modal #form');
      await form.locator('#quickEntry').fill(entry);
      await form.locator('[name="type"]').selectOption(type);
      await form.locator('.quick-details > summary').click();
      await form.locator('[name="status"]').selectOption(status);
      await form.locator('[name="category"]').selectOption('Compras');
      if (type === 'transfer') await form.locator('[name="toAccount"]').selectOption('bank');
      const before = (await saved()).transactions.length;
      await form.locator('.quick-save').click();
      await page.waitForFunction(({ key, count }) => JSON.parse(localStorage.getItem(key)).transactions.length > count, { key, count: before });
    };
    await saveMovement('Compra A 1500', 'expense');
    await saveMovement('Ingreso B 15000', 'income');
    await saveMovement('Traslado C 1500000', 'transfer');
    let db = await saved();
    assert.deepEqual(db.transactions.map(t => t.amount), [1500, 15000, 1500000]);
    const balances = () => page.evaluate(() => ({ cash: accountBalance('cash'), bank: accountBalance('bank'), total: total() }));
    assert.deepEqual(await balances(), { cash: 513500, bank: 2500000, total: 3013500 });

    await page.locator(`${nav} [data-page="Listas"]`).click();
    await page.locator('.wish-entry').click();
    await page.locator('[data-action="newWish"]').click();
    await page.locator('#form [name="name"]').fill('Deseo ficticio');
    await page.locator('#form [name="estimate"]').fill('2000');
    await page.locator('#form [name="category"]').selectOption('Compras');
    await page.locator('#form [name="subcategory"]').fill('Equipo');
    await page.locator('#form [name="list"]').selectOption('home');
    await page.locator('#form [name="goalId"]').selectOption('goal');
    await page.locator('#form [name="account"]').selectOption('cash');
    await page.locator('#form button[type="submit"]').click();
    db = await saved(); const wishId = db.wishes[0].id;
    assert.equal(db.transactions.length, 3);
    assert.deepEqual(await balances(), { cash: 513500, bank: 2500000, total: 3013500 });
    await page.locator('.wish-row [data-action="wishMenu"]').click();
    await page.locator('[data-action="purchaseWish"]').click();
    await page.locator('#modal #quickEntry').fill('Deseo ficticio 1234,56');
    assert.equal(await page.locator('#modal #quickEntry').inputValue(), 'Deseo ficticio 1.234,56');
    assert.equal(await page.locator('#modal [name="wishId"]').inputValue(), wishId);
    await page.locator('#modal .quick-save').click();
    await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).transactions.length === 4, key);
    db = await saved();
    const purchase = db.transactions.find(t => t.wishId === wishId);
    assert.equal(purchase.amount, 1234.56);
    assert.equal(purchase.subcategory, 'Equipo');
    assert.equal(db.wishes[0].estimate, 2000);
    assert.equal(db.goals[0].saved, 300);
    const afterPurchase = await balances();
    assert.ok(Math.abs(afterPurchase.cash - 512265.44) < 1e-8);
    assert.equal(afterPurchase.bank, 2500000);
    assert.ok(Math.abs(afterPurchase.total - 3012265.44) < 1e-8);
    const spent = db.transactions.filter(t => t.type === 'expense' && t.category === 'Compras').reduce((sum, t) => sum + t.amount, 0);
    assert.ok(Math.abs(spent - 2734.56) < 1e-8);

    await page.locator('.wish-row [data-action="wishMenu"]').click();
    await page.locator('[data-action="wishMovement"]').click();
    assert.equal(await page.locator('#modal #quickEntry').inputValue(), 'Deseo ficticio 1.234,56');
    await page.locator('#modal .quick-save').click();
    assert.equal((await saved()).transactions.find(t => t.id === purchase.id).amount, 1234.56);
    assert.equal((await saved()).transactions.length, 4);
    await page.locator('.wish-row [data-action="wishMenu"]').click();
    await page.locator('[data-action="wishMovement"]').click();
    await page.locator('#modal #quickEntry').fill('Deseo ficticio 1500');
    await page.locator('#modal .quick-save').click();
    await page.waitForFunction(({ key, id }) => JSON.parse(localStorage.getItem(key)).transactions.find(t => t.id === id)?.amount === 1500, { key, id: purchase.id });
    db = await saved();
    assert.equal(db.transactions.length, 4);
    assert.equal(db.transactions.find(t => t.id === purchase.id).wishId, wishId);
    await openNew();
    await page.locator('#modal #quickEntry').fill('Duplicado ficticio 1500');
    await page.locator('#modal [name="wishId"]').evaluate((input, id) => { input.value = id; }, wishId);
    await page.locator('#modal .quick-save').click();
    assert.match(await page.locator('#modal #saveNotice').textContent(), /ya tiene un movimiento/);
    assert.equal((await saved()).transactions.length, 4);
    if (width < 1024) await page.locator('#modal .quick-close').click();

    const downloadPromise = page.waitForEvent('download');
    await page.evaluate(() => saveFile());
    const backup = JSON.parse(fs.readFileSync(await (await downloadPromise).path(), 'utf8'));
    assert.equal(backup.transactions.find(t => t.id === purchase.id).wishId, wishId);
    assert.equal(backup.wishes[0].id, wishId);
    await page.locator('.wish-row [data-action="wishMenu"]').click();
    await page.locator('[data-action="editWish"]').click();
    await page.locator('#modal #form [name="estimate"]').fill('2100');
    await page.locator('#modal #form button[type="submit"]').click();
    assert.equal((await saved()).wishes[0].estimate, 2100);
    const chooserPromise = page.waitForEvent('filechooser');
    await page.evaluate(() => importFile());
    const chooser = await chooserPromise;
    page.once('dialog', dialog => dialog.accept());
    await chooser.setFiles({ name: 'integracion-ficticia.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).wishes[0].estimate === 2000, key);
    assert.equal((await saved()).transactions.find(t => t.id === purchase.id).wishId, wishId);
    await page.locator(`${nav} [data-page="Inicio"]`).click();
    await page.locator('[data-action="showHistory"]').click();
    assert.equal(await page.locator('.history-month').count(), 1);
    assert.equal(await page.locator(`.transaction[data-id="${purchase.id}"]`).count(), 1);
    await page.locator(`.transaction[data-id="${purchase.id}"] [data-action="actions"]`).click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-action="delete"]').click();
    db = await saved();
    assert.equal(db.transactions.find(t => t.id === purchase.id).deleted, true);
    await page.locator(`${nav} [data-page="Listas"]`).click();
    await page.locator('.wish-entry').click();
    assert.match(await page.locator('.wish-row').textContent(), /Pendiente/);
    assert.equal(db.transactions.length, 4);
    await openNew();
    await page.locator('#modal #quickEntry').fill('Recurrente ficticio 1234,56');
    const details = page.locator('#modal .quick-details');
    if (!await details.evaluate(element => element.open)) await details.locator('summary').first().click();
    await page.locator('#modal [name="repeat"]').selectOption('monthly');
    const habitualDetails = page.locator('#modal .recurrence-habitual');
    if (!await habitualDetails.evaluate(element => element.open)) await habitualDetails.locator('summary').first().click();
    await page.locator('#modal [name="recurrenceAmount"]').fill('25000,50');
    await page.locator('#modal .quick-save').click();
    await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).transactions.some(t => t.title === 'Recurrente ficticio'), key);
    db = await saved();
    const recurring = db.transactions.find(t => t.title === 'Recurrente ficticio');
    assert.equal(recurring.amount, 1234.56);
    assert.equal(recurring.recurrenceAmount, 25000.5);
    assert.equal(db.transactions.filter(t => t.recurrenceParentId === recurring.id).length, 1);
    assert.equal(db.transactions.find(t => t.recurrenceParentId === recurring.id).wishId, '');
    const beforeEdit = db.revision;
    await page.evaluate(id => transactionForm(id), recurring.id);
    assert.equal(await page.locator('#modal #quickEntry').inputValue(), 'Recurrente ficticio 1.234,56');
    assert.equal(await page.locator('#modal [name="recurrenceAmount"]').inputValue(), '25.000,5');
    await page.locator('#modal .quick-save').click();
    await page.waitForFunction(({ key, beforeEdit }) => JSON.parse(localStorage.getItem(key)).revision > beforeEdit, { key, beforeEdit });
    db = await saved();
    assert.equal(db.transactions.find(t => t.id === recurring.id).amount, 1234.56);
    assert.equal(db.transactions.find(t => t.id === recurring.id).recurrenceAmount, 25000.5);
    assert.equal(db.transactions.filter(t => t.recurrenceParentId === recurring.id).length, 1);
    assert.deepEqual(errors, []);
    console.log(`ok - integración de importes, deseos, saldos e historial a ${width}px`);
  } finally { await browser.close(); }
}

(async () => { for (const width of [375, 1280]) await run(width); })().catch(error => { console.error(error); process.exitCode = 1; });
